"""Regenerates the target-menu markup in frontend/index.html from backend/vocab.py.

    python tools/gen_class_menus.py
"""
import html
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
import vocab  # noqa: E402

BEGIN, END = "<!-- CLASS-MENUS:BEGIN (generated by tools/gen_class_menus.py - do not edit by hand) -->", "<!-- CLASS-MENUS:END -->"
LABEL = {"tv": "TV", "id card": "ID Card", "cell phone": "Cell Phone", "hair drier": "Hair Drier"}
DEFAULT_ON = {"person", "car"}
I = "                    "


def label(n: str) -> str:
    return LABEL.get(n) or " ".join(w.capitalize() for w in n.split())


def build() -> str:
    o = [BEGIN, f'<div id="class-chips-container" data-mode="auto">',
         f'{I}<div class="scope-toggle" role="radiogroup" aria-label="Detection scope">',
         f'{I}  <button type="button" class="scope-opt" data-scope="auto" role="radio" aria-pressed="true"><b>&#10022; Auto</b><span>Finds everything in the picture by itself</span></button>',
         f'{I}  <button type="button" class="scope-opt" data-scope="pick" role="radio" aria-pressed="false"><b>&#9678; Choose targets</b><span>Only look for what I select below</span></button>',
         f'{I}</div>',
         f'{I}<div class="class-presets">',
         f'{I}  <button type="button" class="class-preset" data-preset="traffic">Traffic</button>',
         f'{I}  <button type="button" class="class-preset" data-preset="animals">All animals</button>',
         f'{I}  <button type="button" class="class-preset" data-preset="all">All {len(vocab.COCO_80)} standard</button>',
         f'{I}  <button type="button" class="class-preset" data-preset="reset">Clear</button>',
         f'{I}</div>',
         f'{I}<div class="mm-grid">']
    for key, title, items in vocab.CATEGORIES:
        o.append(f'{I}  <div class="mm" data-cat="{key}">')
        o.append(f'{I}    <button type="button" class="mm-btn" aria-haspopup="true" aria-expanded="false"><span class="mm-title">{html.escape(title)}</span>'
                 f'<span class="mm-count" data-total="{len(items)}">0 / {len(items)}</span>'
                 '<svg class="mm-chev" viewBox="0 0 24 24" fill="none" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"><path d="M6 9l6 6 6-6"/></svg></button>')
        o.append(f'{I}    <div class="mm-panel" role="group" aria-label="{html.escape(title)}">')
        o.append(f'{I}      <input type="search" class="mm-search" placeholder="Search {html.escape(title.lower())}&hellip;" autocomplete="off" spellcheck="false" />')
        o.append(f'{I}      <div class="mm-actions"><button type="button" data-act="all">Select all</button><button type="button" data-act="none">Clear</button></div>')
        o.append(f'{I}      <div class="mm-items">')
        for n in items:
            on = "true" if n in DEFAULT_ON else "false"
            o.append(f'{I}        <button type="button" class="mm-item" data-class="{html.escape(n)}" data-label="{html.escape(label(n))}" aria-pressed="{on}"><span class="mm-box"></span>{html.escape(label(n))}</button>')
        o.append(f'{I}      </div>')
        o.append(f'{I}    </div>')
        o.append(f'{I}  </div>')
    o += [f'{I}</div>',
          f'{I}<div class="mm-selected" aria-live="polite"><span class="mm-selected-label" id="mm-selected-label">Selected targets</span><div class="mm-tags" id="mm-tags"></div></div>',
          f'{I}<div class="smart-hint" id="mm-hint">Auto looks for about {len(vocab.UNIVERSAL_VOCAB)} kinds of things (animals, vehicles, tools, food, furniture&hellip;). Switch to <b>Choose targets</b> if you only want specific ones.</div>',
          "</div>", END]
    return "\n".join(o)


def main():
    p = ROOT / "frontend" / "index.html"
    s = p.read_text(encoding="utf-8")
    block = build()
    if BEGIN in s:
        s = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: block, s, flags=re.S)
    else:  # first run: replace the old hand-written chip block
        a = s.index('<div id="class-chips-container">')
        b = s.index('<div class="form-group form-group-full" id="smart-options">')
        # keep the closing </div> of the form-group that sits just before smart-options
        tail = s[a:b]
        close = tail.rindex("</div>")  # form-group close
        s = s[:a] + block + "\n                " + tail[close:] + s[b:]
    p.write_text(s, encoding="utf-8")
    print("menus written:", sum(len(i) for _, _, i in vocab.CATEGORIES), "items")


if __name__ == "__main__":
    main()
